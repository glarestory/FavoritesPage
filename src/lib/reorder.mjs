/**
 * Returns a new list where the item `sourceId` takes the position of
 * `targetId`. Returns the original list when nothing would change.
 */
export function moveItemToTarget(list, sourceId, targetId) {
  const from = list.findIndex((item) => item.id === sourceId)
  const to = list.findIndex((item) => item.id === targetId)
  if (from < 0 || to < 0 || from === to) return list
  const next = [...list]
  const [moved] = next.splice(from, 1)
  next.splice(to, 0, moved)
  return next
}
